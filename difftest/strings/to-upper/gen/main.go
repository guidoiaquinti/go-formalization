// Command gen emits the nonidentity simple uppercase map from the pinned Go tables.
package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"runtime"
	"strings"
	"unicode"
)

func main() {
	pin, err := os.ReadFile(".go-version")
	if err != nil {
		log.Fatal(err)
	}
	if expected := "go" + strings.TrimSpace(string(pin)); runtime.Version() != expected {
		log.Fatalf("expected %s, got %s", expected, runtime.Version())
	}
	out := bufio.NewWriter(os.Stdout)
	fmt.Fprintln(out, "-- Generated by difftest/strings/to-upper/gen. DO NOT EDIT.")
	fmt.Fprintf(out, "-- Nonidentity unicode.ToUpper pairs from Go %s, Unicode %s.\n\n",
		strings.TrimSpace(string(pin)), unicode.Version)
	fmt.Fprintln(out, "namespace GoLean.Strings\n\ndef simpleUpperData : String :=")
	var words []string
	for r := rune(0); r <= unicode.MaxRune; r++ {
		next := unicode.ToUpper(r)
		if next == r {
			continue
		}
		words = append(words, fmt.Sprint(int64(r)*(unicode.MaxRune+1)+int64(next)))
	}
	for i := 0; i < len(words); i += 12 {
		end := min(i+12, len(words))
		last := ""
		if end < len(words) {
			last = " "
		}
		fmt.Fprintf(out, "  %q", strings.Join(words[i:end], " ")+last)
		if end < len(words) {
			fmt.Fprintln(out, " ++")
		} else {
			fmt.Fprintln(out)
		}
	}
	fmt.Fprintln(out, "\nend GoLean.Strings")
	if err := out.Flush(); err != nil {
		log.Fatal(err)
	}
}
