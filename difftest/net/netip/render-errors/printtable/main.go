// Generate the Lean printable character ranges from the pinned Go Unicode tables.
package main

import (
	"fmt"
	"log"
	"strconv"
	"unicode"
)

func main() {
	fmt.Println("/- Generated by difftest/net/netip/render-errors/printtable using pinned Go. -/")
	fmt.Println("namespace GoLean.Strconv")
	fmt.Println()
	fmt.Println("def printRanges : Array (Nat × Nat) := #[")
	var inside bool
	var start rune
	for r := rune(0); r <= unicode.MaxRune+1; r++ {
		printable := unicode.IsPrint(r)
		if printable != strconv.IsPrint(r) {
			log.Fatalf("printability tables disagree at U+%04X", r)
		}
		switch {
		case printable && !inside:
			start = r
		case inside && !printable:
			fmt.Printf("  (0x%x, 0x%x),\n", start, r-1)
		}
		inside = printable
	}
	fmt.Println("]")
	fmt.Println()
	fmt.Println("end GoLean.Strconv")
}
