package main

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"
)

type leanExecutable struct {
	Name string `json:"name"`
	Root string `json:"root"`
}

var executableName = regexp.MustCompile(`^godiff(-[a-z0-9]+)*$`)
var moduleName = regexp.MustCompile(`^GoDiff(\.[A-Za-z][A-Za-z0-9_]*)+$`)

func readExecutable(path string) (leanExecutable, error) {
	var exe leanExecutable
	data, err := os.ReadFile(path)
	if err != nil {
		return exe, err
	}
	if err := json.Unmarshal(data, &exe); err != nil {
		return exe, fmt.Errorf("%s: %w", path, err)
	}
	if !executableName.MatchString(exe.Name) || !moduleName.MatchString(exe.Root) {
		return exe, fmt.Errorf("%s: invalid executable name or Lean module", path)
	}
	return exe, isFile("lean/" + strings.ReplaceAll(exe.Root, ".", "/") + ".lean")
}

func lakeConfig() (string, error) {
	base, err := os.ReadFile("lean/lakefile.base.toml")
	if err != nil {
		return "", err
	}
	exes := map[string]leanExecutable{}
	err = filepath.WalkDir("difftest", func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || entry.Name() != "lean-exe.json" {
			return nil
		}
		exe, err := readExecutable(path)
		if err != nil {
			return err
		}
		if err := isFile(filepath.Join(filepath.Dir(path), "check.go")); err != nil {
			return err
		}
		if _, exists := exes[exe.Name]; exists {
			return fmt.Errorf("%s: duplicate executable %s", path, exe.Name)
		}
		exes[exe.Name] = exe
		return nil
	})
	if err != nil {
		return "", err
	}
	names := sortedKeys(exes)
	var config strings.Builder
	fmt.Fprintln(&config, "# Generated by make lake-update. Edit lakefile.base.toml or a driver's lean-exe.json.")
	// defaultTargets must precede the first TOML table.
	fmt.Fprint(&config, "defaultTargets = [\"GoLean\"")
	for _, name := range names {
		fmt.Fprintf(&config, ", %q", name)
	}
	fmt.Fprintf(&config, "]\n%s", base)
	for _, name := range names {
		fmt.Fprintf(&config, "\n[[lean_exe]]\nname = %q\nroot = %q\n", name, exes[name].Root)
	}
	return config.String(), nil
}

func syncLakeConfig(update bool) error {
	const path = "lean/lakefile.toml"
	config, err := lakeConfig()
	if err != nil {
		return err
	}
	if data, err := os.ReadFile(path); err == nil && string(data) == config {
		return nil
	}
	if !update {
		return fmt.Errorf("stale %s. Run make lake-update", path)
	}
	return os.WriteFile(path, []byte(config), 0644)
}

func buildDifferentials(checks map[string]map[string]bool, all bool) error {
	args := []string{"build"}
	if !all {
		targets := map[string]bool{}
		for _, path := range sortedKeys(checks) {
			exe, err := readExecutable(filepath.Join(filepath.Dir(path), "lean-exe.json"))
			if err != nil {
				return err
			}
			targets[exe.Name] = true
		}
		if len(targets) == 0 {
			return nil
		}
		args = append(args, sortedKeys(targets)...)
	}
	cmd := exec.Command("lake", args...)
	cmd.Dir = "lean"
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("build Lean executables: %w", err)
	}
	return nil
}
