type declaration struct {
	Package, Symbol, File string
	Line                  int
}

func inventory(version string, targets []target) ([]declaration, error) {
	args := []string{"run", "./scripts/inventory.go"}
	for _, t := range targets {
		args = append(args, t.patterns()...)
	}
	cmd := exec.Command("go", args...)
	cmd.Env = append(os.Environ(), "GOTOOLCHAIN=go"+version, "GOWORK=off", "GOENV=off", "GOOS=", "GOARCH=", "GOEXPERIMENT=", "GOFLAGS=", "CGO_ENABLED=0")
	cmd.Stderr = os.Stderr
	data, err := cmd.Output()
	if err != nil {
		return nil, err
	}
	var rows []declaration
	if err := json.Unmarshal(data, &rows); err != nil {
		return nil, err
	}
	slices.SortFunc(rows, func(a, b declaration) int {
		if c := cmp.Compare(a.Package, b.Package); c != 0 {
			return c
		}
		return cmp.Compare(a.Symbol, b.Symbol)
	})
	return rows, nil
}

type counts struct{ total, started, faithful int }

func thousands(n int) string {
	s := strconv.Itoa(n)
	for i := len(s) - 3; i > 0; i -= 3 {
		s = s[:i] + "," + s[i:]
	}
	return s
}

func (c counts) metrics() string {
	return fmt.Sprintf("%s | %s | %s | %.3f%%", thousands(c.total), thousands(c.started), thousands(c.faithful), 100*float64(c.faithful)/float64(c.total))
}

func report(version string, targets []target, totals map[string]counts, records map[symbol]evidence) (string, error) {
	var s strings.Builder
	fmt.Fprintf(&s, "# Scoped verification progress\n\nThe inventory uses Go %s on a Linux/amd64 (v1) reference profile with cgo disabled and default experiments. Differential checks run on the native host. Each named function or method declared in a selected production Go file counts once, including unexported functions and declarations with assembly implementations. Tests, closures and interface method signatures are excluded.\n\n", version)
	s.WriteString("Started counts functions with a recorded model. Reviewed progress counts declarations with a current FAITHFUL verdict for the recorded claim. The percentage measures review progress across the selected declarations. Each claim below states its scope and execution configuration.\n\n")
	s.WriteString("| Target | Verification focus | Declarations | Started | FAITHFUL | Reviewed progress |\n| --- | --- | ---: | ---: | ---: | ---: |\n")
	groups := map[string]counts{}
	for _, t := range targets {
		c := totals[t.Name]
		if c.total == 0 {
			return "", fmt.Errorf("no source declarations discovered for %s", t.Name)
		}
		group := "Selected standard library"
		if strings.HasPrefix(t.Name, "cmd/") {
			group = "Selected compiler toolchain"
		}
		g := groups[group]
		groups[group] = counts{g.total + c.total, g.started + c.started, g.faithful + c.faithful}
		fmt.Fprintf(&s, "| [%s](https://github.com/golang/go/tree/go%s/src/%s) | %s | %s |\n", t.Name, version, t.Name, t.Focus, c.metrics())
	}
	for _, name := range []string{"Selected standard library", "Selected compiler toolchain"} {
		if g := groups[name]; g.total > 0 {
			fmt.Fprintf(&s, "| **%s total** | | %s |\n", name, g.metrics())
		}
	}
	s.WriteString("\n## Package scope\n\n")
	for _, t := range targets {
		if t.Packages != nil {
			fmt.Fprintf(&s, "- `%s` includes `%s`.\n", t.Name, strings.Join(t.Packages, "`, `"))
		}
	}
	s.WriteString("\nOther targets cover their named package. Use `make inventory TARGET=slices` to list function names, verification states and pinned source lines for one target.\n\n## Verification records\n\n")
	keys := slices.Collect(maps.Keys(records))
	slices.SortFunc(keys, func(a, b symbol) int {
		if order := cmp.Compare(a.Package, b.Package); order != 0 {
			return order
		}
		return cmp.Compare(a.Name, b.Name)
	})
	for _, key := range keys {
		r := records[key]
		fmt.Fprintf(&s, "### %s.%s (%s)\n\n", key.Package, key.Name, r.state)
		for _, detail := range []string{r.Claim, r.Limits, r.Configurations} {
			if detail != "" {
				fmt.Fprintf(&s, "%s\n\n", detail)
			}
		}
		if r.Review != "" {
			fmt.Fprintf(&s, "[Review history](../%s)\n\n", r.Review)
		}
	}
	return strings.TrimRight(s.String(), "\n") + "\n", nil
}

func leanRegistry(records map[symbol]evidence) string {
	modules, theorems := map[string]bool{}, map[string]bool{}
	for _, r := range records {
		module := strings.TrimSuffix(strings.TrimPrefix(r.Model, "lean/"), ".lean")
		modules[strings.ReplaceAll(module, "/", ".")] = true
		for _, name := range r.Theorems {
			theorems[fmt.Sprintf("(``%s, ``%s)", r.ModelSymbol, name)] = true
		}
	}
	var s strings.Builder
	s.WriteString("-- Generated by make coverage-update.\n")
	for _, m := range sortedKeys(modules) {
		fmt.Fprintf(&s, "import %s\n", m)
	}
	fmt.Fprintf(&s, "\ndef GoLean.registeredTheorems : List (Lean.Name × Lean.Name) :=\n  [%s]\n", strings.Join(sortedKeys(theorems), ",\n   "))
	return s.String()
}
